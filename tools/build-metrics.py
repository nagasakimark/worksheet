#!/usr/bin/env python3
"""Writes js/metrics.js: advance widths (per 1000 em) of the New Horizon handwriting fonts,
so the layout can measure words exactly without waiting for the browser.
Usage: python3 tools/build-metrics.py   (needs: pip install fonttools)
"""
import json, os
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def widths(name):
    t = TTFont(os.path.join(ROOT, 'fonts', 'nh', name))
    hm = t['hmtx']
    return {chr(code): hm[g][0] for code, g in sorted(t.getBestCmap().items())}


rl = widths('RL-Light.ttf')
tw = widths('RLTW-Light.ttf')
assert rl == tw, 'RL and RLTW widths differ'
data = {
    'upm': 1000,
    # vertical guide lines (font units, y up from the baseline)
    'lines': {'top': 805, 'mid': 489, 'base': -43, 'bottom': -366},
    'rl': rl,
    'medium': widths('Medium.ttf'),
}
out = os.path.join(ROOT, 'js', 'metrics.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('// Generated by tools/build-metrics.py from fonts/nh/*.ttf - do not edit.\n')
    f.write('window.NH_METRICS = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('wrote', out)
